#!/usr/bin/env python3
"""Generate compact EU artwork edge ownership from the five audited recipes."""
import argparse
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('directory', type=Path, help='directory containing eu-1-complete.json through eu-5-complete.json')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
audits = [json.loads((args.directory / f'eu-{i}-complete.json').read_text()) for i in range(1, 6)]
assert all(a['region'] == 'EU' and a['rom_sha256'] ==
           'c84645731952b7677f514ae222683504066334ab2af904e64a8a84ffc1af46c6' for a in audits)
fixtures = [a['images'] for a in audits]
# Old retained audits predate the native -120 credits scroll correction.
for fixture in fixtures:
    for name in ('credits_02', 'credits_03', 'credits_06', 'credits_07'):
        assert fixture[name]['layer_mask'] == 0x24 and fixture[name]['palette_bank_mask'] == 0x7f81, name
source = (root / 'port/port_screen_background.c').read_text()
mapping = dict(re.findall(r'\[(PORT_BACKGROUND_\w+)\] = \{ PORT_BACKGROUND_SOURCE_IMAGE, "([^"]+)\.png" \}', source))
assert len(mapping) == len(fixtures[0]) == 33
lines = ['/* Generated by tools/generate_background_edge_coverage.py from the five EU recipe audits. */',
         'static const PortBackgroundArtworkEdges sArtworkEdges[PORT_BACKGROUND_COUNT] = {']
for context, name in mapping.items():
    edges = fixtures[0][name]['edges']
    assert all(f[name]['edges'] == edges for f in fixtures[1:]), name
    lines.append(f'    [{context}] = {{')
    for side in ('left', 'right', 'top', 'bottom'):
        values = edges[side]
        assert len(values) == (160 if side in ('left', 'right') else 240) and all(0 <= v < 96 for v in values)
        lines.append('        {')
        for i in range(0, len(values), 20):
            lines.append('            ' + ', '.join(str(v) for v in values[i:i+20]) + ',')
        lines.append('        },')
    lines.append('    },')
lines += ['};', 'static const bool sArtworkEdgeValid[PORT_BACKGROUND_COUNT] = {']
lines += [f'    [{context}] = true,' for context in mapping]
lines += ['};', '']
output = root / 'port/port_background_edges.inc'
text = '\n'.join(lines)
if args.check:
    if output.read_text() != text:
        raise SystemExit('edge data does not match the five audited recipes')
else:
    output.write_text(text)
